# Faça as contas e tente desvendar o mistério. Se possível, coloque os tipos que cada variável é.
cinco = 5
era = 6
delta = 25 % cinco
alfa = 24 // 3
reinos = (cinco * era * 10 - 100) // alfa
morte = 2 + delta - ( 3 % alfa )
guerras = reinos + alfa - ( 23 % era)
salao = reinos ^ (7 << 2)
lua = (guerras & 7) >> 1
tempo = (salao * era )
theta = (tempo >> lua) ^ 0b100 
medo = (~ (16 | 14) & (salao << lua) ) * morte

print(delta)     # 0
print(alfa)      # 8
print(reinos)    # 25
print(morte)     # -1
print(guerras)   # 28
print(salao)     # 5
print(lua)       # 2
print(tempo)     # 30
print(theta)     # 3
print(medo)      # 0





